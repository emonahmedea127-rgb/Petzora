  <li><strong>Alternating Forelimb Stepping:</strong> The cat shifts its body weight smoothly between left and right front legs in a rhythmic, quasi-hypnotic tempo. Some cats also engage their hind feet, performing a subtle four-paw "tread."</li>
  <li><strong>Claw Extension and Retraction:</strong> As each paw presses downward, the digital flexor tendons tighten, causing the claws to spread and extend outward. As the paw lifts, elastic ligaments pull the claws safely back into their sheaths.</li>
  <li><strong>Rhythmic Purring:</strong> The laryngeal muscles vibrate in sync with the paw movements, signaling active parasympathetic nervous system engagement.</li>
  <li><strong>Softening Facial Posture:</strong> The cat’s eyes typically become heavy-lidded or half-shut, with whiskers resting flat and relaxed against the cheeks.</li>
  <li><strong>Occasional Hypersalivation (Drooling):</strong> In deeply relaxed cats, involuntary salivary flow increases, resulting in clear moisture pooling around the mouth.</li>
</ul>

